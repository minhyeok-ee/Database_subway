    # 모든 역 이름 -> Station 테이블에 삽입
    all_stations = set()
    for stations in LINE_DATA.values():
        for st in stations:
            all_stations.add(st)

    for st in all_stations:
        cursor.execute("""
            INSERT OR IGNORE INTO Station (Station_name)
            VALUES (?);
        """, (st,))
    
    db.commit()

    # 라인 추가 + Route 데이터 추가
    for line_name, stations in LINE_DATA.items():

        # 라인 추가
        cursor.execute("""
            INSERT OR IGNORE INTO Line (name)
            VALUES (?);
        """, (line_name,))
        db.commit()

        # Line_id 가져오기
        cursor.execute("SELECT Line_id FROM Line WHERE name = ?;", (line_name,))
        line_id = cursor.fetchone()[0]

        # Route 테이블에 순서대로 삽입
        for seq, station_name in enumerate(stations, start=1):
            cursor.execute("SELECT Station_id FROM Station WHERE Station_name = ?;", (station_name,))
            station_id = cursor.fetchone()[0]

            cursor.execute("""
                INSERT OR REPLACE INTO Route (Line_id, Station_id, Sequence)
                VALUES (?, ?, ?);
            """, (line_id, station_id, seq))

        db.commit()

    print("=== 데이터베이스 로드 완료 ===")

